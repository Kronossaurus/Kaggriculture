"""Extract one player's per-step action sequence from a downloaded Kaggle
replay JSON into a standalone "tape agent" .py file -- the same technique
reference/x492_nah_i_d_win.py uses internally (replay a precomputed
per-step action list every turn), just sourced from a real competitor's
game instead of an offline solve. Lets `run_local.py`/`pool_winrate.py`
test main.py against how an actual strong human-submitted bot played
(aggressive early hiring, real sell timing, animal use), which the
built-in pool (random/starter/melon_maxxer/x492) can't approximate --
x492 itself is a tape too, but its own author's tape, tuned for its own
play, not a general "how do real competitors open" reference.

Get a replay to extract from via `data/AGENTS.md`'s Download Replays and
Logs section:
    uv run kaggle competitions submissions kaggriculture   # find a SUBMISSION_ID
    uv run kaggle competitions episodes <SUBMISSION_ID>     # find an EPISODE_ID
    uv run kaggle competitions replay <EPISODE_ID> -p ./replays

CAVEAT -- read before trusting results against this tape: it's only a
faithful reproduction of the ORIGINAL game, seed and all. The instant the
paired agent's actions diverge from what the original opponent did (they
will, turn 1+, since main.py isn't a replay of the original game), the
market/farm state this tape's later actions were computed against no
longer matches reality -- a later SELL/FEED/PLACE order may reference
produce, seeds, or animals the replayed player no longer actually has by
that point, which the engine silently no-ops (data/README.md: invalid
actions are no-ops, never errors). Early-game structure (hiring pace, land
timing, opening crop mix) stays representative; late-game precision
degrades the longer the game runs. Useful as a stress opponent for
opening-game behavior, not a perfect clone of the original player.

Only ever valid at the seed it was recorded with -- pool_winrate.py's
seeds 1..N sweep doesn't apply; test with run_local.py's --seed instead
(see this script's own printed usage line at the end).

Usage:
    uv run scripts/extract_replay_tape.py <replay.json> <player_index> <out.py>
    uv run scripts/extract_replay_tape.py replays/kaggle_submission/episode-94006627-replay.json 0 reference/tape_valmrnch.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

_PASS_ACTION = {"farmer": ["PASS"], "hands": [], "market": []}


def main() -> None:
    if len(sys.argv) != 4:
        print(__doc__)
        raise SystemExit(1)
    replay_path, player_idx, out_path = sys.argv[1], int(sys.argv[2]), Path(sys.argv[3])

    with open(replay_path, encoding="utf-8") as f:
        data = json.load(f)
    steps = data["steps"]
    tape = [step[player_idx].get("action") or _PASS_ACTION for step in steps]

    info = data.get("info", {})
    team_name = (info.get("TeamNames") or ["?", "?"])[player_idx]
    episode_id = info.get("EpisodeId", "?")
    seed = info.get("seed", "?")

    source = f'''"""Tape-replay agent extracted from a real Kaggle episode -- team
{team_name!r}, episode {episode_id}, seed {seed}. Replays the exact
recorded action sequence turn by turn; not reactive, doesn't look at
`obs` beyond day/hour. Generated by scripts/extract_replay_tape.py --
see that script's docstring for the divergence caveat (only faithful
against the seed it was recorded with, and only faithful early -- once
the opponent it's paired against plays differently than the original
game, later actions may reference resources this replay no longer
actually has, silently no-op'd by the engine).

Only valid at seed={seed}:
    uv run scripts/run_local.py --p2 {out_path.as_posix()} --seed {seed}
"""

_TAPE = {tape!r}


def agent(obs, configuration=None):
    day = int(obs.get("day", 0) or 0)
    hour = int(obs.get("hour", 0) or 0)
    turns_per_day = 24
    if configuration is not None:
        get = configuration.get if isinstance(configuration, dict) else lambda k, d: getattr(configuration, k, d)
        turns_per_day = int(get("turnsPerDay", 24) or 24)
    step = min(max(0, day * turns_per_day + hour), len(_TAPE) - 1)
    return _TAPE[step]
'''
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(source, encoding="utf-8")
    print(f"Wrote {out_path} ({len(tape)} steps, team={team_name!r}, episode={episode_id}, seed={seed})")
    print(f"Test with: uv run scripts/run_local.py --p2 {out_path.as_posix()} --seed {seed}")


if __name__ == "__main__":
    main()
